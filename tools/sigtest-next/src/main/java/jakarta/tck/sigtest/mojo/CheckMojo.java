package jakarta.tck.sigtest.mojo;

import jakarta.tck.sigtest.check.SignatureChecker;
import jakarta.tck.sigtest.check.Violation;
import jakarta.tck.sigtest.model.SignatureRecord;
import jakarta.tck.sigtest.util.PackageUtil;
import jakarta.tck.sigtest.util.SignatureIO;
import org.apache.maven.artifact.Artifact;
import org.apache.maven.plugin.AbstractMojo;
import org.apache.maven.plugin.MojoExecutionException;
import org.apache.maven.plugin.MojoFailureException;
import org.apache.maven.plugins.annotations.Component;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.plugins.annotations.ResolutionScope;
import org.apache.maven.project.MavenProject;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Checks the public API of a dependency artifact against a previously generated
 * {@code .sig.json} baseline file, failing the build if any incompatibility is found.
 *
 * <p>Every aspect of the API contract — class kinds, modifiers, superclasses,
 * interfaces, methods, constructors, and fields — is checked in a single pass.
 * The check is strict: additions to the API are violations just like removals
 * and changes.
 *
 * <h2>Minimal configuration</h2>
 * <pre>{@code
 * <plugin>
 *   <groupId>jakarta.tck</groupId>
 *   <artifactId>sigtest-next-plugin</artifactId>
 *   <version>1.0-SNAPSHOT</version>
 *   <executions>
 *     <execution>
 *       <goals><goal>check</goal></goals>
 *     </execution>
 *   </executions>
 *   <configuration>
 *     <groupId>jakarta.servlet</groupId>
 *     <artifactId>jakarta.servlet-api</artifactId>
 *     <!-- path to the baseline produced by sigtest-next:generate -->
 *     <sigfile>${project.basedir}/src/test/signature/jakarta.servlet-api.sig.json</sigfile>
 *   </configuration>
 * </plugin>
 * }</pre>
 */
@Mojo(
        name = "check",
        defaultPhase = LifecyclePhase.TEST,
        requiresDependencyResolution = ResolutionScope.COMPILE
)
public class CheckMojo extends AbstractMojo {

    @Component
    private MavenProject project;

    /**
     * {@code groupId} of the dependency artifact to scan.
     */
    @Parameter(required = true)
    private String groupId;

    /**
     * {@code artifactId} of the dependency artifact to scan.
     */
    @Parameter(required = true)
    private String artifactId;

    /**
     * Path to the baseline {@code .sig.json} file generated by
     * {@code sigtest-next:generate}.
     */
    @Parameter(required = true)
    private File sigfile;

    /**
     * Comma-separated list of package prefixes to exclude from the scan.
     * When empty, the excludes stored in the baseline (written by
     * {@code sigtest-next:generate}) are used; an explicit value overrides them.
     */
    @Parameter(defaultValue = "")
    private String excludes;

    /**
     * When {@code true} (the default), fail the build if any incompatibility is
     * found. Set to {@code false} to report violations without failing.
     */
    @Parameter(defaultValue = "true", property = "sigtest.failOnError")
    private boolean failOnError;

    // -------------------------------------------------------------------------

    @Override
    public void execute() throws MojoExecutionException, MojoFailureException {
        // 1. Validate inputs.
        if (!sigfile.isFile()) {
            throw new MojoExecutionException(
                    "Baseline signature file not found: " + sigfile.getAbsolutePath()
                    + ". Run sigtest-next:generate first.");
        }

        // 2. Locate the target artifact JAR.
        Artifact target = resolveArtifact();
        File jar = target.getFile();
        if (jar == null || !jar.isFile()) {
            throw new MojoExecutionException(
                    "Artifact " + groupId + ":" + artifactId + " has no associated file. "
                    + "Ensure it is listed as a compile-scope dependency.");
        }

        // 3. Load baseline.
        SignatureRecord baseline = loadBaseline(sigfile);

        Set<String> excludePackages = PackageUtil.parsePackages(excludes);

        getLog().info("sigtest-next:check scanning: " + jar.getName());
        getLog().info("sigtest-next:check baseline: " + sigfile.getName());

        List<File> classpath = buildClasspath();
        List<Violation> violations;
        try {
            violations = SignatureChecker.check(baseline, jar, classpath, excludePackages);
        } catch (IOException e) {
            throw new MojoExecutionException("Failed to scan " + jar + ": " + e.getMessage(), e);
        }

        // 4. Report.
        getLog().info("sigtest-next:check — " + violations.size() + " violation(s) found");
        for (Violation v : violations) {
            getLog().info(v.toString());
        }

        if (!violations.isEmpty() && failOnError) {
            throw new MojoFailureException(
                    "API signature check failed with " + violations.size() + " incompatibility(ies). "
                    + "See the log above for details.");
        }
    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    private Artifact resolveArtifact() throws MojoExecutionException {
        for (Artifact a : project.getArtifacts()) {
            if (groupId.equals(a.getGroupId()) && artifactId.equals(a.getArtifactId())) {
                return a;
            }
        }
        throw new MojoExecutionException(
                "Could not find artifact " + groupId + ":" + artifactId
                + " in the project's resolved dependencies. Add it as a <dependency> with scope 'compile'.");
    }

    private SignatureRecord loadBaseline(File file) throws MojoExecutionException {
        try {
            return SignatureIO.load(file);
        } catch (IOException e) {
            throw new MojoExecutionException(e.getMessage(), e);
        }
    }

    private List<File> buildClasspath() {
        List<File> cp = new ArrayList<>();
        for (Artifact a : project.getArtifacts()) {
            if (a.getFile() != null && a.getFile().exists()) {
                cp.add(a.getFile());
            }
        }
        return cp;
    }
}
